const {buildSync}=require('esbuild');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const {Window}=await import(pathToFileURL(path.resolve('.sites-runtime/drag-test-tools/node_modules/happy-dom/lib/index.js')));
 const win=new Window({url:'https://board.test/login'});
 globalThis.window=win;globalThis.document=win.document;globalThis.sessionStorage=win.sessionStorage;
 let reduced=false;
 win.matchMedia=()=>({matches:reduced});
 let animated=0;
 const animate=()=>{animated++;return{finished:Promise.resolve()}};
 win.HTMLElement.prototype.animate=animate;win.SVGElement.prototype.animate=animate;
 globalThis.requestAnimationFrame=callback=>{callback(performance.now()+2000);return 1};
 buildSync({entryPoints:['app/login-transition.ts'],bundle:true,platform:'node',format:'cjs',outfile:'.sites-runtime/login-transition-tests.cjs'});
 const {navigateWithLogo,installBoardEntrance,transitionShell}=require(path.resolve('.sites-runtime/login-transition-tests.cjs'));
 document.body.innerHTML='<img class="login-mark">';
 await navigateWithLogo('/?card=task-123');
 assert.equal(new URL(win.location.href).searchParams.get('card'),'task-123');
 assert(Number(sessionStorage.getItem('marketing-login-entrance'))>0);
 assert.equal(animated,2);
 document.body.innerHTML=transitionShell+'<div id="marketing-root"></div>';
 document.documentElement.classList.add('luke-entering');
 installBoardEntrance();
 assert.equal(document.getElementById('marketing-root').inert,true);
 assert.equal(sessionStorage.getItem('marketing-login-entrance'),null);
 win.dispatchEvent(new win.Event('marketing-board-ready'));
 assert.equal(document.querySelector('.login-reveal-stage'),null);
 assert.equal(document.getElementById('marketing-root').inert,false);
 assert.equal(document.documentElement.classList.contains('luke-entering'),false);
 // Reloads without a recent successful login never show the transition.
 document.body.innerHTML=transitionShell+'<div id="marketing-root"></div>';
 installBoardEntrance();assert.equal(document.querySelector('.login-reveal-stage'),null);
 sessionStorage.setItem('marketing-login-entrance',String(Date.now()-60000));
 document.body.innerHTML=transitionShell+'<div id="marketing-root"></div>';
 installBoardEntrance();assert.equal(document.querySelector('.login-reveal-stage'),null);
 reduced=true;
 await navigateWithLogo('/');
 assert.equal(sessionStorage.getItem('marketing-login-entrance'),null);
 assert.equal(animated,2);
 assert.equal(new URL(win.location.href).pathname,'/');
 console.log('PASS: successful-login animation, deep-link destination, one-use recent marker, board-ready reveal, focus recovery, expired markers and reduced motion.');
})().catch(error=>{console.error(error);process.exitCode=1});
